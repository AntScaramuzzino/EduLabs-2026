// Generate attendance records for completed sessions
export const generateInitialAttendance = (): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const students = INITIAL_USERS.filter(u => u.role === 'student');

  INITIAL_SESSIONS.forEach(session => {
    const courseStudents = students.filter(s => s.enrolledCourseIds.includes(session.courseId));

    courseStudents.forEach((student, idx) => {
      let status: 'present' | 'late' | 'absent' | 'excused' = 'present';
      let attendedHours = session.hours;
      let checkinTime: string | undefined = '15:31:05';
      let verifiedByPin = true;

      if (!session.isCompleted) {
        // live session
        if (idx === 0) {
          status = 'present';
          checkinTime = '15:30:45';
        } else if (idx === 1) {
          status = 'late';
          checkinTime = '15:45:12';
          attendedHours = 2.0;
        } else {
          status = 'absent';
          checkinTime = undefined;
          attendedHours = 0;
          verifiedByPin = false;
        }
      } else {
        // Historical sessions:
        // Student 3 (Tommaso Esposito) has more absences in course-1 (to test threshold warning < 70%)
        if (student.id === 'student-3' && session.courseId === 'course-1' && (session.sessionNumber === 3 || session.sessionNumber === 5)) {
          status = 'absent';
          attendedHours = 0;
          checkinTime = undefined;
          verifiedByPin = false;
        } else if (student.id === 'student-4' && session.courseId === 'course-1' && session.sessionNumber === 4) {
          status = 'excused';
          attendedHours = session.hours;
          checkinTime = undefined;
          verifiedByPin = false;
        } else if (student.id === 'student-5' && session.sessionNumber % 2 === 0) {
          status = 'late';
          attendedHours = Math.max(0.5, session.hours - 0.5);
          checkinTime = '15:48:20';
        }
      }

      records.push({
        id: `att-${session.id}-${student.id}`,
        sessionId: session.id,
        courseId: session.courseId,
        studentId: student.id,
        status,
        checkinTime,
        attendedHours,
        verifiedByPin: false,
        validatedByEducator: true,
        validatedByInstructor: true,
        notes: status === 'excused' ? 'Assenza giustificata dalla famiglia (motivi sanitari)' : undefined,
        updatedAt: new Date().toISOString(),
      });
    });
  });

  return records;
};

